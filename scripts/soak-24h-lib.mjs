// Computes the Phase 0 soak metrics from a Token Watcher analytics JSON export
// (debug view -> Export JSON) using the formulas in
// docs/product-hunt/baseline/METRICS_CONTRACT.md. Pure: no I/O.
const pct = v => (v == null ? 'unknown' : `${(v * 100).toFixed(1)}%`);
const iso = ms => new Date(ms).toISOString();

export function parseExport(text) {
  const data = JSON.parse(text);
  if (data?.schemaVersion !== 1 || !Array.isArray(data.events)) throw new Error('not a schemaVersion 1 analytics export');
  return data;
}

// markers: { startAt, endAt, restartedAt?, networkCutAt?, networkRestoredAt? } as epoch ms.
export function computeSoak(data, markers) {
  const { startAt, endAt } = markers;
  if (!(endAt > startAt)) throw new Error('window end must be after start');
  const inWindow = data.events.filter(e => e.ts >= startAt && e.ts <= endAt);
  const refreshes = inWindow.filter(e => e.name === 'refresh_result').sort((a, b) => a.ts - b.ts);
  const excluded = refreshes.filter(e => e.props.errorCategory === 'provider_tab_missing');
  const counted = refreshes.filter(e => e.props.errorCategory !== 'provider_tab_missing');
  const ok = counted.filter(e => e.props.ok);
  const staleEnded = inWindow.filter(e => e.name === 'stale_ended');
  const unexplained = staleEnded.filter(e => !e.props.explained);
  const staleStarted = inWindow.filter(e => e.name === 'stale_started');
  // A stale_started with no later stale_ended for the provider is still open at window end.
  const open = staleStarted.filter(s => !staleEnded.some(e => e.props.provider === s.props.provider && e.ts >= s.ts));

  const recovery = at => {
    if (at == null) return { status: 'not recorded' };
    const next = refreshes.find(e => e.ts >= at && e.props.ok);
    return next ? { status: 'measured', seconds: Math.round((next.ts - at) / 1000), at } : { status: 'no successful refresh after marker', at };
  };
  return {
    window: { startAt, endAt, hours: (endAt - startAt) / 3600000 },
    refreshAttempts: refreshes.length,
    excludedProviderTabMissing: excluded.length,
    denominator: counted.length,
    successes: ok.length,
    successRate: counted.length ? ok.length / counted.length : null,
    staleEndedCount: staleEnded.length,
    unexplainedStaleEnded: unexplained.length,
    unexplainedStaleRate: staleEnded.length ? unexplained.length / staleEnded.length : null,
    maxUnexplainedStaleSeconds: unexplained.length ? Math.max(...unexplained.map(e => e.props.staleSeconds)) : (staleEnded.length ? 0 : null),
    maxStaleSeconds: staleEnded.length ? Math.max(...staleEnded.map(e => e.props.staleSeconds)) : null,
    openStaleAtEnd: open.length,
    openStaleUnexplained: open.filter(s => !s.props.explained).length,
    restartRecovery: recovery(markers.restartedAt),
    networkRestoreRecovery: recovery(markers.networkRestoredAt),
    networkCutAt: markers.networkCutAt ?? null,
    requiredMarkersMissing: ['restartedAt', 'networkCutAt', 'networkRestoredAt'].filter(k => markers[k] == null),
  };
}

export function renderReport(r, { buildSha, exportedAt, notes = '' }) {
  const rec = x => x.status === 'measured' ? `${x.seconds} s (${x.seconds <= 600 ? 'within' : 'EXCEEDS'} the 600 s criterion)` : x.status;
  return `# Phase 0 soak report: 24 hour real-browser run

Generated by \`node scripts/soak-24h-report.mjs\` from a Token Watcher analytics export. Definitions: \`docs/product-hunt/baseline/METRICS_CONTRACT.md\`.

- Build SHA: \`${buildSha}\`
- UTC window: ${iso(r.window.startAt)} to ${iso(r.window.endAt)} (${r.window.hours.toFixed(2)} h${r.window.hours < 24 ? ', **shorter than 24 h**' : ''})
- Export taken: ${exportedAt}
- Network cut at: ${r.networkCutAt == null ? 'not recorded' : iso(r.networkCutAt)}
${r.requiredMarkersMissing.length ? `\n**Missing markers: ${r.requiredMarkersMissing.join(', ')}. The restart/offline requirement is not demonstrated.**\n` : ''}
## Results

| Metric | Value |
| --- | --- |
| Refresh attempts in window | ${r.refreshAttempts} |
| Excluded (\`provider_tab_missing\`, per contract) | ${r.excludedProviderTabMissing} |
| Denominator (counted attempts) | ${r.denominator} |
| Successful refreshes | ${r.successes} |
| Refresh success rate | ${pct(r.successRate)} |
| Stale intervals ended | ${r.staleEndedCount} |
| Unexplained stale intervals | ${r.unexplainedStaleEnded} (${pct(r.unexplainedStaleRate)}) |
| Max unexplained stale interval | ${r.maxUnexplainedStaleSeconds == null ? 'unknown (no stale intervals)' : `${r.maxUnexplainedStaleSeconds} s`} |
| Max stale interval (any cause) | ${r.maxStaleSeconds == null ? 'unknown (no stale intervals)' : `${r.maxStaleSeconds} s`} |
| Stale intervals still open at window end | ${r.openStaleAtEnd} (${r.openStaleUnexplained} unexplained); not included in the max above |
| Recovery after browser restart | ${rec(r.restartRecovery)} |
| Recovery after network restore | ${rec(r.networkRestoreRecovery)} |

## Exclusions and limits

- Per-install, on-device data; this is one install, not the beta cohort, so it does not answer exit criterion 1.
- Only events inside the UTC window are counted. Events are pruned at 90 days / 5000 events; the export must cover the whole window.
- Recovery = first successful \`refresh_result\` at or after the marker, minus the marker time (markers are supplied by the operator, not logged by the extension).
${notes}`;
}
