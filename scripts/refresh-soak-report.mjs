#!/usr/bin/env node
// Runs the accelerated refresh soak and writes docs/reliability/refresh-soak.md.
// Usage: node scripts/refresh-soak-report.mjs [hours] [seed]
import { writeFileSync, mkdirSync } from 'node:fs';
import { runSoak } from '../claudewatch-extension/test/refresh-soak.mjs';

const hours = Number(process.argv[2] ?? 24);
const seed = Number(process.argv[3] ?? 20261022);
const r = runSoak({ hours, seed });
const pct = v => (v == null ? 'unknown' : `${(v * 100).toFixed(1)}%`);
const counts = r.faults.reduce((m, f) => ({ ...m, [f.kind]: (m[f.kind] ?? 0) + 1 }), {});

const md = `# Refresh reliability: accelerated soak (Prompt 0.2)

Generated by \`npm run soak:refresh\` (seed ${seed}, ${hours} simulated hours). Deterministic: the same seed gives the same numbers.

**What this is.** The real \`claudewatch-extension/refresh-policy.js\` decisions (\`evaluate\`, \`applyOutcome\`, \`staleInfo\`) driven by a fake one-minute clock against a simulated provider with injected faults. **What this is not.** It is not a 24 hour run in a real browser against real providers; those components (alarms, tab events, collectors) are not exercised here. It is not Phase 0 gate evidence.

## Injected faults

${Object.entries(counts).map(([k, n]) => `- ${k}: ${n} windows`).join('\n')}

## Measured results

| Metric | Value |
| --- | --- |
| Refresh attempts | ${r.attempts} |
| Successful refreshes | ${r.successes} |
| Refresh success rate (all attempts, including those during injected outages) | ${pct(r.successRate)} |
| Refresh success rate when no fault was active (${r.availableAttempts} attempts) | ${pct(r.successRateWhenUpstreamAvailable)} |
| Total stale time | ${r.totalStaleMinutes} min |
| Maximum stale interval (any cause) | ${r.maxStaleMinutes} min |
| Maximum unexplained stale interval (no recorded reason) | ${r.maxUnexplainedStaleMinutes} min |
| Maximum unexplained stale interval while the worker was running | ${r.maxUnexplainedStaleWhileWorkerRunningMinutes} min |

"Unexplained" means the reading was older than the 15 minute stale threshold and the state had no recorded failure category (reason \`scheduler_gap\` or \`not_attempted\`). The simulated \`worker_suspended\` windows drop all alarms, which is harsher than Chrome, where alarms wake a suspended service worker; unexplained time inside those windows is the cost of the worker not running at all.
`;
mkdirSync(new URL('../docs/reliability/', import.meta.url), { recursive: true });
writeFileSync(new URL('../docs/reliability/refresh-soak.md', import.meta.url), md);
console.log(md);
