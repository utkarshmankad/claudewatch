// Aggregates the legs of a browser soak (directories holding samples.jsonl, events.jsonl, leg.json) into one report.
//   node scripts/soak/report.mjs <out.md> <legDir> [<legDir> ...]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

import { readdirSync, statSync } from 'node:fs';

const [outFile, ...roots] = process.argv.slice(2);
if (!outFile || roots.length === 0) { console.error('usage: report.mjs <out.md> <dir>...'); process.exit(2); }

// Every directory under the roots that holds a samples.jsonl is a leg. (A single downloaded artifact lands directly in the
// target directory; several land in one sub-directory each.)
function findLegs(dir, out = []) {
  if (!existsSync(dir) || !statSync(dir).isDirectory()) return out;
  if (existsSync(path.join(dir, 'samples.jsonl'))) out.push(dir);
  for (const name of readdirSync(dir)) findLegs(path.join(dir, name), out);
  return out;
}
const dirs = [...new Set(roots.flatMap((r) => findLegs(r)))].sort();
if (dirs.length === 0) { console.error(`no leg directories (samples.jsonl) under: ${roots.join(', ')}`); process.exit(1); }

const lines = (f) => (existsSync(f) ? readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : []);
const samples = dirs.flatMap((d) => lines(path.join(d, 'samples.jsonl'))).sort((a, b) => a.t - b.t);
const events = dirs.flatMap((d) => lines(path.join(d, 'events.jsonl'))).sort((a, b) => Date.parse(a.at) - Date.parse(b.at));
const legs = dirs.map((d) => (existsSync(path.join(d, 'leg.json')) ? JSON.parse(readFileSync(path.join(d, 'leg.json'), 'utf8')) : null)).filter(Boolean);
if (samples.length < 2) { console.error('not enough samples'); process.exit(1); }

const gaps = samples.slice(1).map((s, i) => s.t - samples[i].t).sort((a, b) => a - b);
const interval = gaps[Math.floor(gaps.length / 2)] || 30_000; // typical sample spacing
const min = (ms) => Math.round((ms / 60_000) * 10) / 10;

// Legs are separated by a browser restart; a long gap between samples is not stale time, so runs break at 5 intervals.
function runs(pred) {
  const out = [];
  let cur = null;
  for (let i = 0; i < samples.length; i += 1) {
    const s = samples[i];
    if (pred(s) && cur && s.t - cur.last <= interval * 5) { cur.last = s.t; cur.n += 1; }
    else if (pred(s)) { if (cur) out.push(cur); cur = { first: s.t, last: s.t, n: 1 }; }
    else if (cur) { out.push(cur); cur = null; }
  }
  if (cur) out.push(cur);
  return out.map((r) => ({ ...r, ms: r.last - r.first + interval }));
}
const staleRuns = runs((s) => s.stale === true);
const unexplainedRuns = runs((s) => s.stale === true && s.explained === false);
const maxMs = (r) => r.reduce((m, x) => Math.max(m, x.ms), 0);

const withState = samples.filter((s) => s.stale !== null);
const fresh = withState.filter((s) => s.stale === false).length;
const noFault = withState.filter((s) => s.fault.length === 0);
const noFaultFresh = noFault.filter((s) => s.stale === false).length;
const unexplainedNoFault = noFault.filter((s) => s.stale === true && s.explained === false).length;
const attempts = samples.filter((s) => s.attemptChanged).length;
const successes = samples.filter((s) => s.successChanged).length;
const readErrors = samples.filter((s) => s.readError).length;

// Recovery: from the moment a cause ended (or a restart began) to the next sample showing a new successful refresh.
function recoveries(startKinds, endEvent) {
  const out = [];
  for (const e of events) {
    if (e.type !== endEvent || !startKinds.includes(e.kind)) continue;
    const t0 = Date.parse(e.at);
    const next = samples.find((s) => s.t >= t0 && s.successChanged);
    out.push({ kind: e.kind, at: e.at, minutes: next ? min(next.t - t0) : null });
  }
  return out;
}
const afterEnd = recoveries(['offline', 'tab_missing', 'session_expired', 'rate_limited', 'schema_changed'], 'fault_end');
const afterRestart = recoveries(['browser_restart', 'worker_stopped'], 'fault_start');
const startedLegs = events.filter((e) => e.type === 'leg_start').length;
const faultsStarted = events.filter((e) => e.type === 'fault_start');
const byKind = {};
for (const f of faultsStarted) byKind[f.kind] = (byKind[f.kind] ?? 0) + 1;
const pct = (a, b) => (b === 0 ? 'n/a' : `${Math.round((a / b) * 1000) / 10}%`);
const slow = [...afterEnd, ...afterRestart].filter((r) => r.minutes == null || r.minutes > 10);
const worst = (r) => (r.length ? Math.max(...r.map((x) => x.minutes ?? Infinity)) : null);

const first = new Date(samples[0].t).toISOString();
const last = new Date(samples.at(-1).t).toISOString();
const spanMin = min(samples.at(-1).t - samples[0].t);
const md = `# Browser refresh soak report

Generated by \`scripts/soak/report.mjs\` from ${dirs.length} leg(s). Real Chromium, the real extension build in \`claudewatch-extension/\`, a fixture provider served in place of chatgpt.com, injected faults. **No real provider, account or credential was involved**, so this is not the Phase 0 beta-cohort measurement and does not replace it.

- Window (UTC): ${first} to ${last} (${spanMin} min of samples, ${samples.length} samples every ~${Math.round(interval / 1000)} s, ${startedLegs} leg start(s))
- Wall-clock run, not simulated time. Faults are dense on purpose (a "safe accelerated schedule"), so rates below are worse than real use.
- Faults injected: ${faultsStarted.length} (${Object.entries(byKind).map(([k, n]) => `${k}: ${n}`).join(', ') || 'none'})
- Provider requests served by the fixture: ${legs.reduce((n, l) => n + (l.providerRequestsServed ?? 0), 0)}

## Measured

| Metric | Value |
| --- | --- |
| Samples with a readable refresh state | ${withState.length} of ${samples.length} (${readErrors} read errors) |
| Refresh attempts seen (state changes between samples; undercounts) | ${attempts} |
| Successful refreshes seen | ${successes} |
| Samples with a fresh reading (all samples, faults included) | ${pct(fresh, withState.length)} |
| Samples with a fresh reading while no fault was active | ${pct(noFaultFresh, noFault.length)} (${noFault.length} samples) |
| Stale samples with no recorded reason while no fault was active | ${unexplainedNoFault} |
| Maximum stale interval, any cause | ${min(maxMs(staleRuns))} min |
| Maximum unexplained stale interval (no recorded reason) | ${min(maxMs(unexplainedRuns))} min |
| Slowest recovery after a fault ended | ${worst(afterEnd) == null ? 'n/a' : `${worst(afterEnd)} min`} (${afterEnd.length} recoveries) |
| Slowest recovery after a browser restart or worker stop | ${worst(afterRestart) == null ? 'n/a' : `${worst(afterRestart)} min`} (${afterRestart.length} events) |
| Recoveries over 10 minutes or never seen | ${slow.length} |

"Unexplained" follows \`refresh-policy.js\`: stale (reading older than 15 minutes) with no recorded failure category. The 10 minute figure is the Phase 0 criterion for recovery after browser startup or network restoration.

## Recoveries

| Event | Started or ended (UTC) | Minutes to next successful refresh |
| --- | --- | --- |
${[...afterEnd.map((r) => ({ ...r, what: `${r.kind} ended` })), ...afterRestart.map((r) => ({ ...r, what: `${r.kind} started` }))].sort((a, b) => Date.parse(a.at) - Date.parse(b.at)).map((r) => `| ${r.what} | ${r.at} | ${r.minutes ?? 'not seen'} |`).join('\n') || '| none | | |'}

## Limits

- Fixture provider only: it proves the scheduling, recovery and persistence paths in a real browser, not that the real providers' pages and APIs behave the same way.
- One provider (ChatGPT collector path through a tab). Claude and Gemini collectors are not exercised here.
- Samples read the extension's persisted refresh state directly, so the measurement does not itself trigger a refresh.
- ${startedLegs === 1 ? 'A single leg: the run is as long as that leg.' : `${startedLegs} legs: each leg closes the browser and the next reopens the same profile.`} A GitHub-hosted runner job is capped at 6 hours, which is why long runs are chained.
`;
writeFileSync(outFile, md);
writeFileSync(outFile.replace(/\.md$/, '.json'), JSON.stringify({ window: { first, last, spanMin, samples: samples.length }, faultsByKind: byKind, attempts, successes, freshAll: pct(fresh, withState.length), freshNoFault: pct(noFaultFresh, noFault.length), maxStaleMin: min(maxMs(staleRuns)), maxUnexplainedMin: min(maxMs(unexplainedRuns)), recoveries: { afterEnd, afterRestart }, slowRecoveries: slow.length }, null, 2));
console.log(md);
